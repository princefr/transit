pub fn decode_feed_message(bytes: &[u8]) -> Result<FeedMessage, prost::DecodeError> {
    use prost::Message;
    FeedMessage::decode(bytes)
}

pub fn apply_trip_updates(feed_id: &str, bytes: &[u8], state: &mut FeedRtState) {
    let msg = match decode_feed_message(bytes) {
        Ok(m) => m,
        Err(e) => {
            warn!(feed_id, error = %e, "failed to decode trip updates");
            return;
        }
    };
    state.trip_updates_fetched_at = Some(Utc::now());
    if let Some(h) = msg.header.timestamp {
        state.header_timestamp = Some(h as i64);
    }
    if msg.header.incrementality() == Incrementality::FullDataset {
        state.trips.clear();
    }

    for entity in msg.entity {
        if entity.is_deleted.unwrap_or(false) {
            // Differential delete: remove by entity trip if we can.
            // Without trip payload we skip (id alone is not our trip map key).
            continue;
        }
        let Some(tu) = entity.trip_update else {
            continue;
        };
        // trip is required message in proto2 → plain struct in prost (always present after decode)
        let trip = tu.trip;
        let raw_trip_id = trip
            .trip_id
            .clone()
            .filter(|s| !s.is_empty())
            .unwrap_or_default();

        // start_date is optional string YYYYMMDD
        let start_date = trip.start_date.clone().filter(|s| !s.is_empty());
        let start_time = trip.start_time.clone().filter(|s| !s.is_empty());
        let route_id = trip
            .route_id
            .as_ref()
            .filter(|s| !s.is_empty())
            .map(|r| format!("{feed_id}:{r}"));
        let direction_id = trip.direction_id;

        // Incomplete entities (no trip_id) need at least route_id to be useful.
        if raw_trip_id.is_empty() && route_id.is_none() {
            continue;
        }

        // schedule_relationship defaults to SCHEDULED when unset
        let canceled = matches!(trip.schedule_relationship(), TripRel::Canceled);

        let mut stop_updates = std::collections::HashMap::new();
        for stu in tu.stop_time_update {
            // stop_sequence optional; 0 is valid but rare — still accept
            let seq = stu.stop_sequence.unwrap_or(0) as u16;
            let stop_id = stu
                .stop_id
                .as_ref()
                .filter(|s| !s.is_empty())
                .map(|s| format!("{feed_id}:{s}"));
            let arrival_delay = stu.arrival.as_ref().and_then(|a| a.delay);
            let departure_delay = stu.departure.as_ref().and_then(|d| d.delay);
            let arrival_time = stu.arrival.as_ref().and_then(|a| a.time);
            let departure_time = stu.departure.as_ref().and_then(|d| d.time);
            let skipped = matches!(stu.schedule_relationship(), StuRel::Skipped);
            stop_updates.insert(
                seq,
                StopTimeRt {
                    stop_sequence: seq,
                    stop_id,
                    arrival_delay,
                    departure_delay,
                    arrival_time,
                    departure_time,
                    skipped,
                },
            );
        }

        // Trip-level delay is optional (seconds)
        let delay = tu.delay;

        state.insert_trip(
            feed_id,
            &raw_trip_id,
            TripRt {
                delay,
                canceled,
                start_date,
                route_id,
                direction_id,
                start_time,
                stop_updates,
            },
        );
    }
    // Count undated keys so dual-insert does not inflate the metric
    state.trip_update_count = state
        .trips
        .keys()
        .filter(|k| !k.contains('@'))
        .count();
}

pub fn apply_vehicle_positions(feed_id: &str, bytes: &[u8], state: &mut FeedRtState) {
    let msg = match decode_feed_message(bytes) {
        Ok(m) => m,
        Err(e) => {
            warn!(feed_id, error = %e, "failed to decode vehicle positions");
            return;
        }
    };
    state.vehicles_fetched_at = Some(Utc::now());
    if let Some(h) = msg.header.timestamp {
        state.header_timestamp = Some(h as i64);
    }
    if msg.header.incrementality() == Incrementality::FullDataset {
        state.vehicles.clear();
    }

    for entity in msg.entity {
        if entity.is_deleted.unwrap_or(false) {
            continue;
        }
        let Some(vp) = entity.vehicle else {
            continue;
        };
        let trip_id = vp
            .trip
            .as_ref()
            .and_then(|t| t.trip_id.clone())
            .filter(|s| !s.is_empty())
            .map(|t| format!("{feed_id}:{t}"));
        let Some(pos) = vp.position else {
            continue;
        };
        // latitude/longitude are required floats in proto2 — default 0.0 if missing
        let lat = pos.latitude as f64;
        let lon = pos.longitude as f64;
        if lat == 0.0 && lon == 0.0 {
            continue;
        }
        let updated_at = vp
            .timestamp
            .and_then(|t| Utc.timestamp_opt(t as i64, 0).single())
            .unwrap_or_else(Utc::now);
        let key = trip_id
            .clone()
            .or_else(|| {
                if entity.id.is_empty() {
                    None
                } else {
                    Some(format!("{feed_id}:{}", entity.id))
                }
            })
            .unwrap_or_else(|| format!("{feed_id}:veh"));
        let veh = vp.vehicle.as_ref();
        let label = veh
            .and_then(|v| v.label.clone())
            .filter(|s| !s.is_empty());
        let vehicle_id = veh
            .and_then(|v| v.id.clone())
            .filter(|s| !s.is_empty());
        let license_plate = veh
            .and_then(|v| v.license_plate.clone())
            .filter(|s| !s.is_empty());

        // Only set enum-backed strings when the wire field is present (not default-filled).
        let occupancy = vp.occupancy_status.map(|_| {
            vp.occupancy_status().as_str_name().to_string()
        });
        let current_status = vp.current_status.map(|_| {
            vp.current_status().as_str_name().to_string()
        });
        let congestion = vp.congestion_level.map(|_| {
            vp.congestion_level().as_str_name().to_string()
        });

        // Prefer vehicle-level occupancy_percentage; else average multi-carriage values ≥ 0.
        let occupancy_percentage = vp.occupancy_percentage.or_else(|| {
            let pcts: Vec<u32> = vp
                .multi_carriage_details
                .iter()
                .filter_map(|c| {
                    c.occupancy_percentage.and_then(|p| {
                        if p >= 0 {
                            Some(p as u32)
                        } else {
                            None
                        }
                    })
                })
                .collect();
            if pcts.is_empty() {
                None
            } else {
                let sum: u32 = pcts.iter().sum();
                Some(sum / pcts.len() as u32)
            }
        });

        state.vehicles.insert(
            key,
            VehiclePos {
                trip_id,
                lat,
                lon,
                bearing: pos.bearing.map(|b| b as f64),
                speed: pos.speed.map(|s| s as f64),
                updated_at,
                current_stop_id: vp
                    .stop_id
                    .as_ref()
                    .filter(|s| !s.is_empty())
                    .map(|s| format!("{feed_id}:{s}")),
                label,
                vehicle_id,
                license_plate,
                occupancy,
                current_status,
                current_stop_sequence: vp.current_stop_sequence,
                congestion,
                occupancy_percentage,
            },
        );
    }
    state.vehicle_count = state.vehicles.len();
}

pub fn apply_service_alerts(feed_id: &str, bytes: &[u8], state: &mut FeedRtState) {
    let msg = match decode_feed_message(bytes) {
        Ok(m) => m,
        Err(e) => {
            warn!(feed_id, error = %e, "failed to decode service alerts");
            return;
        }
    };
    state.alerts_fetched_at = Some(Utc::now());
    if let Some(h) = msg.header.timestamp {
        state.header_timestamp = Some(h as i64);
    }
    if msg.header.incrementality() == Incrementality::FullDataset {
        state.alerts.clear();
    }

    for entity in msg.entity {
        if entity.is_deleted.unwrap_or(false) {
            continue;
        }
        let Some(alert) = entity.alert else {
            continue;
        };
        let id = if entity.id.is_empty() {
            format!("{feed_id}:alert:{}", state.alerts.len())
        } else {
            entity.id.clone()
        };
        let header_translations: Vec<(String, String)> = alert
            .header_text
            .as_ref()
            .map(|t| {
                t.translation
                    .iter()
                    .filter(|tr| !tr.text.is_empty())
                    .map(|tr| {
                        (
                            tr.language.clone().unwrap_or_default(),
                            tr.text.clone(),
                        )
                    })
                    .collect()
            })
            .unwrap_or_default();
        let desc_translations: Vec<(String, String)> = alert
            .description_text
            .as_ref()
            .map(|t| {
                t.translation
                    .iter()
                    .filter(|tr| !tr.text.is_empty())
                    .map(|tr| {
                        (
                            tr.language.clone().unwrap_or_default(),
                            tr.text.clone(),
                        )
                    })
                    .collect()
            })
            .unwrap_or_default();
        // Prefer French (not first language — SNCF often ships DE first + HTML).
        let header = crate::rt::alert_text::pick_translation(&header_translations);
        let description = crate::rt::alert_text::pick_translation(&desc_translations);

        let mut informed_stop_ids = Vec::new();
        let mut informed_route_ids = Vec::new();
        let mut informed_trip_ids = Vec::new();
        for ie in &alert.informed_entity {
            if let Some(ref s) = ie.stop_id {
                if !s.is_empty() {
                    informed_stop_ids.push(format!("{feed_id}:{s}"));
                }
            }
            if let Some(ref r) = ie.route_id {
                if !r.is_empty() {
                    informed_route_ids.push(format!("{feed_id}:{r}"));
                }
            }
            if let Some(t) = ie.trip.as_ref().and_then(|tr| tr.trip_id.as_ref()) {
                if !t.is_empty() {
                    informed_trip_ids.push(format!("{feed_id}:{t}"));
                }
            }
        }

        let severity = match alert.severity_level() {
            pb::alert::SeverityLevel::Severe => "SEVERE",
            pb::alert::SeverityLevel::Warning => "WARNING",
            pb::alert::SeverityLevel::Info => "INFO",
            _ => "INFO",
        }
        .to_string();

        let cause = alert
            .cause
            .map(|_| alert.cause().as_str_name().to_string());
        let effect = alert
            .effect
            .map(|_| alert.effect().as_str_name().to_string());
        let url = alert
            .url
            .as_ref()
            .and_then(|t| t.translation.first())
            .map(|tr| tr.text.clone())
            .filter(|s| !s.is_empty());

        // All active_period ranges; keep first as active_start/end for compat.
        #[allow(deprecated)]
        let active_periods: Vec<(Option<i64>, Option<i64>)> = alert
            .active_period
            .iter()
            .map(|tr| (tr.start.map(|s| s as i64), tr.end.map(|e| e as i64)))
            .collect();
        let (active_start, active_end) = active_periods
            .first()
            .copied()
            .unwrap_or((None, None));

        state.alerts.push(AlertRt {
            id: format!("{feed_id}:{id}"),
            header,
            description,
            severity,
            informed_stop_ids,
            informed_route_ids,
            informed_trip_ids,
            cause,
            effect,
            url,
            active_start,
            active_end,
            active_periods,
            header_translations,
        });
    }
    state.alert_count = state.alerts.len();
}

