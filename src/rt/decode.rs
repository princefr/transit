    #[test]
    fn decode_trip_update_delay_and_dual_key() {
        let bytes = encode_trip_update_feed(
            Some("TRIP42"),
            Some("20240601"),
            Some(30),
            false,
            5,
            180,
            false,
            Some("R99"),
            Some(1),
            Some("12:30:00"),
        );
        let mut state = FeedRtState::new("idf");
        apply_trip_updates("idf", &bytes, &mut state);

        assert!(state.trips.contains_key("idf:TRIP42"));
        assert!(state.trips.contains_key("idf:TRIP42@20240601"));
        assert_eq!(state.trip_update_count, 1);

        let t = state.get_trip("idf:TRIP42").unwrap();
        assert_eq!(t.delay, Some(30));
        assert!(!t.canceled);
        assert_eq!(t.start_date.as_deref(), Some("20240601"));
        assert_eq!(t.route_id.as_deref(), Some("idf:R99"));
        assert_eq!(t.direction_id, Some(1));
        assert_eq!(t.start_time.as_deref(), Some("12:30:00"));
        let stu = t.stop_updates.get(&5).unwrap();
        assert_eq!(stu.arrival_delay, Some(180));
        assert_eq!(stu.stop_id.as_deref(), Some("idf:S1"));
        assert!(!stu.skipped);
    }

