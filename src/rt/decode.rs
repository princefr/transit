//! GTFS-RT protobuf decode using prost-generated types.
//!
//! # Prost + proto2 quirks
//!
//! The official GTFS-realtime schema is **proto2**. With prost:
//!
//! - **Required** scalar/message fields become plain non-`Option` fields (e.g.
//!   `TripUpdate.trip`, `Position.latitude` / `longitude`). They still decode
//!   as defaults (0 / empty) if the wire message omitted them — we must not
//!   assume presence and should skip invalid entities (empty `trip_id`,
//!   0,0 position).
//! - **Optional** scalars/messages become `Option<T>` and may be `None`.
//! - **Enum** fields: use the generated `*_or_default` / accessor methods
//!   (e.g. `schedule_relationship()`) rather than unwrapping raw integers.
//! - **`is_deleted`** on feed entities is optional; treat missing as false.
//! - **Full dataset** vs differential: when `header.incrementality` is
//!   `FULL_DATASET` (default in many feeds), clear the relevant map before
//!   applying entities.
//!
//! # Trip key strategy
//!
//! Each trip is stored as `feed_id:trip_id`. When `start_date` is present and
//! non-empty, the same [`TripRt`] is also inserted as
//! `feed_id:trip_id@YYYYMMDD` (see [`FeedRtState::insert_trip`]).

